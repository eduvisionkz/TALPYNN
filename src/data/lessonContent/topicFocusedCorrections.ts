export function applyTopicFocusedCorrections(lesson: TopicLessonContent): TopicLessonContent {
  const revision = TOPIC_FOCUSED_REVISIONS[`${lesson.grade}-${lesson.track}-${lesson.title}`]
  if (!revision) return lesson
  const [content, answer, distractors, explanation] = revision
  const task: BekitTask = {
    kind: 'multiple_choice', title: 'Тақырып бойынша таңда', content,
    options: [{ text: answer, correct: true }, ...distractors.map(text => ({ text, correct: false }))],
    explanation, hint: 'Тақырыптағы негізгі ережені еске түсір.',
  }
  return { ...lesson, bekit: lesson.bekit.map((existing, i) => i === 4 ? task : existing) }
}
